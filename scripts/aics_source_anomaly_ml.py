"""Causal, online unsupervised anomaly learning on pre-existing AICS research scores.

No labels/no supervised market forecasts. Every observation is scored from
earlier source-eligible events of the SAME node, then added to training.
Scores generated by old ex-post-selected rules are not pre-registered OOS.
This module never feeds back into AICS node weights or investment signals.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import math
import statistics
from pathlib import Path

from scripts.aics_score_reproducibility_gate import WEIGHTS

V17 = Path("aics_data/research/aics_24m_multi_node_publication_overlay_2026-11-21.json")
V18 = Path("aics_data/research/aics_v18_private_credit_24m_pit_proxy_overlay_2026-11-22.json")
DEFAULT_OUT = Path("aics_data/agent_runs/online_anomaly_research.json")
MIN_TRAINING = 8
TRAINING_WINDOW = 16
ANOMALY_THRESHOLD = 3.5


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def observed_events(v17, v18):
    if (v17.get("schema") != "aics-24m-multi-node-first-public-date-research-overlay-v1"
            or v18.get("schema") != "aics-v18-24m-private-credit-original-sec-expost-research-overlay-v1"
            or v18.get("scores_are_expost_not_preregistered") is not True
            or v17.get("independently_historical_pit_attested") is not False
            or v18.get("historical_pit_source_bytes_independently_attested") is not False):
        raise ValueError("Uncertified historical source lineage expected")
    observations = []
    for e in v17["source_events"]:
        observations.append({
            "node": e["node"], "available": e["research_eligible_date"],
            "score": e["score"], "source": e["source"],
            "source_policy": e.get("source_policy"),
        })
    for e in v18["source_events"]:
        observations.append({
            "node": e["node"], "available": e["research_available_at_proxy"],
            "score": e["score"],
            "source": "aics_data/research/private_credit_2024q2_2026q1_first_sec_cost_breadth_2026-11-22.json",
            "source_policy": "retrospective_2026_directional_formula",
        })
    return observations


def online_learn(observations, *, as_of=None, min_training=MIN_TRAINING):
    """Prequential median/MAD anomaly learner: new event never trains itself.

    Events with the same node/publication day train together only AFTER all
    forecasts for that day. No fabricated rows, no unseen future observations.
    """
    as_of = as_of or dt.date.today()
    if not isinstance(as_of, dt.date) or isinstance(as_of, dt.datetime):
        raise ValueError("Explicit as_of must be a calendar date")
    if min_training < MIN_TRAINING:
        raise ValueError("Minimum historical evidence gate cannot be loosened")
    parsed = []
    seen = set()
    for e in observations:
        if e["node"] not in WEIGHTS:
            raise ValueError("Unknown AICS node")
        when = dt.date.fromisoformat(e["available"])
        score = float(e["score"])
        if not math.isfinite(score) or not 0 <= score <= 100:
            raise ValueError("Original 0..100 source-derived score required")
        if when > as_of:
            continue
        key = (e["node"], e["available"], e["source"], e["score"])
        if key in seen:
            raise ValueError("Duplicated original node/date/score/source event")
        seen.add(key)
        parsed.append((when, e["node"], score, e["source"]))
    parsed.sort(key=lambda r: (r[0], r[1], r[3]))
    histories = {n: [] for n in WEIGHTS}
    reports = []
    idx = 0
    while idx < len(parsed):
        day = parsed[idx][0]
        end = idx
        while end < len(parsed) and parsed[end][0] == day:
            end += 1
        # One publication day is one chronological information batch.
        for date, node, score, source in parsed[idx:end]:
            train = histories[node][-TRAINING_WINDOW:]
            report = {
                "node": node, "source_eligible_at": date.isoformat(),
                "original_score": score, "source": source,
                "prior_observations": len(train), "model": "online_robust_median_mad_v1",
                "training_max_date": train[-1][0].isoformat() if train else None,
                "model_status": "cold_start", "anomaly_z": None,
                "model_alert": None, "independently_pit_attested": False,
                "pre_registered_historical_model": False,
            }
            if len(train) >= min_training and len({r[0] for r in train}) >= min_training:
                values = [r[1] for r in train]
                mid = statistics.median(values)
                mad = statistics.median(abs(x - mid) for x in values)
                report["prior_median"] = round(mid, 4)
                report["prior_mad"] = round(mad, 4)
                if mad == 0:
                    report["model_status"] = "unscaled_constant_baseline"
                    if score != mid:
                        report["model_alert"] = "unscaled_distribution_change_research"
                else:
                    z = 0.67448975 * (score - mid) / mad
                    report["model_status"] = "causal_research_assessed"
                    report["anomaly_z"] = round(z, 4)
                    if abs(z) >= ANOMALY_THRESHOLD:
                        report["model_alert"] = ("positive_stress_anomaly_research"
                                                 if z > 0 else "negative_stress_anomaly_research")
            reports.append(report)
        for date, node, score, _ in parsed[idx:end]:
            histories[node].append((date, score))
        idx = end
    counts = {n:len(histories[n]) for n in WEIGHTS}
    alerts = [x for x in reports if x["model_alert"] is not None]
    return {
        "schema": "aics-causal-online-unsupervised-source-anomaly-v1",
        "as_of": as_of.isoformat(), "model_type": "unsupervised_online_robust_baseline",
        "min_prior_distinct_source_dates": min_training,
        "max_prior_train_events": TRAINING_WINDOW,
        "anomaly_z_threshold": ANOMALY_THRESHOLD,
        "research_events_evaluated": len(reports),
        "learned_prior_node_event_counts": counts,
        "events_with_trainable_history": sum(
            r["model_status"] in ("causal_research_assessed", "unscaled_constant_baseline")
            for r in reports),
        "research_attention_events": len(alerts),
        "alerts": alerts,
        "sample_decisions": reports,
        "pre_registered_out_of_sample": False,
        "source_delivery_historically_pit_attested": False,
        "supervised_return_targets": None,
        "predictive_accuracy": None, "sp500_excess_return_skill": None,
        "supervised_prediction_status": "BLOCKED_UNTIL_REALIZED_LABELS_AND_FROZEN_OOS",
        "complete_11_node_index": None, "trades_created": False,
        "aics_weights_changed": False, "production_model_changed": False,
        "limitations": [
            "Original 0..100 stress proxy transformations were researched ex post",
            "Unsupervised novelty detection is not a market-return prediction",
            "Each observation is evaluated only against strictly earlier publication dates",
            "No historical source provider receipt timestamps independently attested",
            "No independent untouched 24-month investment performance validation",
        ],
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    p.add_argument("--as-of", default=dt.date.today().isoformat())
    args = p.parse_args()
    report = online_learn(observed_events(read(V17), read(V18)),
                          as_of=dt.date.fromisoformat(args.as_of))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(json.dumps({
        "observed_events": report["research_events_evaluated"],
        "model_trained_events": report["events_with_trainable_history"],
        "attention_flags": report["research_attention_events"],
        "supervised_returns_prediction": "blocked", "aics_index": None,
    }))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
