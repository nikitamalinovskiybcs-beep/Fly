import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)


class QuantConnectIntegration:
    """Integration with QuantConnect LEAN engine.

    Two modes:
    1. CLOUD: Use QC API (free: 10 backtests/month, 1 live algo)
    2. LOCAL: Clone LEAN engine, run unlimited backtests locally
    """

    QC_API_URL = "https://www.quantconnect.com/api/v2"

    def __init__(self, user_id: str = "", api_token: str = "") -> None:
        self._user_id = user_id
        self._api_token = api_token
        self._enabled = bool(user_id and api_token)

        if not self._enabled:
            logger.info("QuantConnect credentials not provided, cloud features disabled")

    @property
    def enabled(self) -> bool:
        return self._enabled

    def export_strategy_to_lean(
        self,
        signal_weights: dict,
        tickers: list[str],
        output_path: str = "strategies/",
    ) -> str:
        """Convert Fly paper trading strategy to LEAN Python algo.

        Args:
            signal_weights: Signal weight dict from paper trader.
            tickers: Watchlist tickers.
            output_path: Directory to write generated file.

        Returns:
            Path to generated strategy file.
        """
        Path(output_path).mkdir(parents=True, exist_ok=True)
        out_file = Path(output_path) / "qc_fly_strategy.py"

        tickers_str = ", ".join(f'"{t}"' for t in tickers)
        weights_str = json.dumps(signal_weights, indent=8)

        code = f'''"""Fly Strategy — auto-generated for QuantConnect LEAN engine.

Generated by Fly paper trading agent.
Signal weights: {json.dumps(signal_weights)}
"""

from AlgorithmImports import *


class FlyStrategy(QCAlgorithm):

    def Initialize(self):
        self.SetStartDate(2023, 1, 1)
        self.SetEndDate(2024, 12, 31)
        self.SetCash(100000)

        self.tickers = [{tickers_str}]
        self.symbols = {{}}
        for t in self.tickers:
            self.symbols[t] = self.AddEquity(t, Resolution.Daily).Symbol

        self.signal_weights = {weights_str}

        self.rsi = {{}}
        self.sma50 = {{}}
        self.sma200 = {{}}
        for t in self.tickers:
            sym = self.symbols[t]
            self.rsi[t] = self.RSI(sym, 14, Resolution.Daily)
            self.sma50[t] = self.SMA(sym, 50, Resolution.Daily)
            self.sma200[t] = self.SMA(sym, 200, Resolution.Daily)

        self.SetWarmUp(200)

    def OnData(self, data):
        if self.IsWarmingUp:
            return

        for ticker in self.tickers:
            sym = self.symbols[ticker]
            if not data.ContainsKey(sym):
                continue

            price = float(data[sym].Close)
            signals = self._collect_signals(ticker, price)
            composite = sum(
                signals.get(k, 0) * self.signal_weights.get(k, 0)
                for k in self.signal_weights
            )

            if composite > 0.3 and not self.Portfolio[sym].Invested:
                self.SetHoldings(sym, 0.20)
            elif composite < -0.3 and self.Portfolio[sym].Invested:
                self.Liquidate(sym)

    def _collect_signals(self, ticker, price):
        signals = {{}}
        rsi_val = self.rsi[ticker].Current.Value if self.rsi[ticker].IsReady else 50

        if rsi_val < 30:
            signals["rsi_oversold"] = 1.0
        elif rsi_val < 40:
            signals["rsi_oversold"] = 0.5
        else:
            signals["rsi_oversold"] = 0.0

        if rsi_val > 70:
            signals["rsi_overbought"] = -1.0
        elif rsi_val > 60:
            signals["rsi_overbought"] = -0.5
        else:
            signals["rsi_overbought"] = 0.0

        sma50_val = self.sma50[ticker].Current.Value if self.sma50[ticker].IsReady else price
        if price > sma50_val * 1.02:
            signals["sma_crossover"] = 1.0
        elif price < sma50_val * 0.98:
            signals["sma_crossover"] = -1.0
        else:
            signals["sma_crossover"] = 0.0

        signals["regime"] = 0.0
        signals["evt_var_safe"] = 1.0
        signals["momentum_30d"] = 0.0
        signals["mean_reversion"] = 0.0
        signals["volume_confirmation"] = 0.0

        return signals
'''
        out_file.write_text(code)
        logger.info("Exported LEAN strategy to %s", out_file)
        return str(out_file)

    def run_cloud_backtest(
        self,
        project_name: str,
        start_date: str,
        end_date: str,
    ) -> dict:
        """Submit backtest to QC cloud.

        Args:
            project_name: Project name on QC.
            start_date: Start date (YYYY-MM-DD).
            end_date: End date (YYYY-MM-DD).

        Returns:
            Backtest results dict.
        """
        if not self._enabled:
            return {"error": "credentials not configured"}
        try:
            import requests
            auth = (self._user_id, self._api_token)

            resp = requests.post(
                f"{self.QC_API_URL}/projects/create",
                auth=auth,
                json={"name": project_name, "language": "Py"},
                timeout=30,
            )
            if resp.status_code != 200:
                return {"error": f"project creation failed: {resp.status_code}"}

            project_id = resp.json().get("projects", [{}])[0].get("projectId")
            return {"project_id": project_id, "status": "created"}
        except Exception as exc:
            return {"error": str(exc)}

    def get_backtest_results(self, backtest_id: str) -> dict:
        """Fetch detailed backtest results.

        Args:
            backtest_id: QC backtest ID.

        Returns:
            Results dict with equity curve, trade log, metrics.
        """
        if not self._enabled:
            return {"error": "credentials not configured"}
        try:
            import requests
            auth = (self._user_id, self._api_token)
            resp = requests.get(
                f"{self.QC_API_URL}/backtests/read",
                auth=auth,
                params={"backtestId": backtest_id},
                timeout=30,
            )
            return resp.json()
        except Exception as exc:
            return {"error": str(exc)}

