    def compare_results(self, fly_stats: dict, qc_stats: dict) -> dict:
        """Compare Fly paper trading vs QuantConnect backtest.

        Args:
            fly_stats: Stats from PaperTradingAgent.get_stats().
            qc_stats: Stats from QC backtest.

        Returns:
            Comparison table dict.
        """
        metrics = ["sharpe_ratio", "total_return", "max_drawdown", "win_rate"]
        comparison = {}
        for m in metrics:
            fly_val = fly_stats.get(m, 0)
            qc_val = qc_stats.get(m, 0)
            comparison[m] = {
                "fly": fly_val,
                "quantconnect": qc_val,
                "diff": round(fly_val - qc_val, 4) if isinstance(fly_val, (int, float)) else None,
            }
        return comparison

